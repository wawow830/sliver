//! The public interfaces must match `docs/dbus/io.github.wawow830.Sliver.xml`, which is the
//! machine-readable half of docs/api.md. Regenerate after an intentional change with
//! `SLIVER_UPDATE_DBUS_XML=1 cargo test -p sliver-api --test introspection`, and bump
//! `API_MINOR` for additive changes (or the interface major for breaking ones).

use sliver_api::identity::RealProc;
use sliver_api::service::{Api, Control, ControlReply, ControlState, Host};
use sliver_ipc::dbus::{BUS_NAME, IFACE_TOUCHBAR, ROOT_PATH};
use std::collections::HashMap;
use std::io::{BufRead, BufReader};
use std::process::{Command, Stdio};
use std::sync::Arc;
use zbus::zvariant::{OwnedObjectPath, OwnedValue};

struct NoHost;
impl Host for NoHost {
    fn changed(&self) {}
    fn control(&self, _: Control) -> Result<ControlReply, String> {
        Ok(ControlReply::Done)
    }
    fn control_state(&self) -> ControlState {
        ControlState::default()
    }
}

/// Only our interfaces, in a stable order.
fn ours(xml: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = xml;
    while let Some(start) = rest.find("<interface name=\"") {
        let end = rest[start..]
            .find("</interface>")
            .map(|e| start + e + "</interface>".len())
            .unwrap();
        let block = &rest[start..end];
        if block.starts_with(&format!("<interface name=\"{BUS_NAME}.")) {
            // Normalize indentation: the same interface shows up at different nesting depths.
            let lines: Vec<String> = block
                .lines()
                .map(|l| {
                    let t = l.trim();
                    let depth = if t.starts_with("<interface") || t.starts_with("</interface") {
                        1
                    } else if t.starts_with("<arg") || t.starts_with("<annotation") {
                        3
                    } else {
                        2
                    };
                    format!("{}{t}", "  ".repeat(depth))
                })
                .collect();
            out.push(lines.join("\n"));
        }
        rest = &rest[end..];
    }
    out.sort();
    out
}

#[test]
fn interfaces_match_docs() {
    let Ok(mut daemon) = Command::new("dbus-daemon")
        .args(["--session", "--nofork", "--print-address=1"])
        .stdout(Stdio::piped())
        .spawn()
    else {
        eprintln!("dbus-daemon not installed; skipping");
        return;
    };
    let mut addr = String::new();
    BufReader::new(daemon.stdout.take().unwrap())
        .read_line(&mut addr)
        .unwrap();
    let addr = addr.trim().to_owned();
    let _api = zbus::block_on(async {
        let conn = zbus::connection::Builder::address(addr.as_str())
            .unwrap()
            .build()
            .await
            .unwrap();
        Api::serve(conn, Arc::new(NoHost), Arc::new(RealProc))
            .await
            .unwrap()
    });
    let c = zbus::blocking::connection::Builder::address(addr.as_str())
        .unwrap()
        .build()
        .unwrap();
    let ctx: OwnedObjectPath = c
        .call_method(
            Some(BUS_NAME),
            ROOT_PATH,
            Some(IFACE_TOUCHBAR),
            "CreateContext",
            &(HashMap::<String, OwnedValue>::new(),),
        )
        .unwrap()
        .body()
        .deserialize()
        .unwrap();
    let introspect = |path: &str| -> String {
        let p = zbus::blocking::fdo::IntrospectableProxy::builder(&c)
            .destination(BUS_NAME)
            .unwrap()
            .path(path)
            .unwrap()
            .build()
            .unwrap();
        p.introspect().unwrap()
    };
    let mut blocks = ours(&introspect(ROOT_PATH));
    blocks.extend(ours(&introspect(ctx.as_str())));
    blocks.sort();
    blocks.dedup();
    let _ = daemon.kill();
    let _ = daemon.wait();

    let generated = format!(
        "<!DOCTYPE node PUBLIC \"-//freedesktop//DTD D-BUS Object Introspection 1.0//EN\"\n \
         \"http://www.freedesktop.org/standards/dbus/1.0/introspect.dtd\">\n\
         <!-- Sliver public session API. Generated by crates/sliver-api/tests/introspection.rs; \
         prose in docs/api.md. -->\n<node>\n{}\n</node>\n",
        blocks.join("\n")
    );
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../docs/dbus/io.github.wawow830.Sliver.xml"
    );
    if std::env::var_os("SLIVER_UPDATE_DBUS_XML").is_some() {
        std::fs::create_dir_all(std::path::Path::new(path).parent().unwrap()).unwrap();
        std::fs::write(path, &generated).unwrap();
        return;
    }
    let documented = std::fs::read_to_string(path).unwrap_or_default();
    assert!(
        documented == generated,
        "D-Bus API drifted from docs/dbus/io.github.wawow830.Sliver.xml. If intended, update docs/api.md, \
         bump API_MINOR, and regenerate with SLIVER_UPDATE_DBUS_XML=1."
    );
}
