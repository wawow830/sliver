#!/usr/bin/env python3
"""Regenerate src/keys_table.rs: input_linux::Key variant names -> Linux keycodes.

Key names in sliver config are the `input_linux::Key` variant names (what tiny-dfr accepts),
matched case-insensitively. Usage:
  gen_keys.py <input-linux-src/keys.rs> /usr/include/linux/input-event-codes.h > src/keys_table.rs
"""
import re, sys

keys_rs, header = sys.argv[1], sys.argv[2]
defs = {}
for line in open(header):
    m = re.match(r"#define\s+(KEY_\w+)\s+(\S+)", line)
    if m:
        defs[m.group(1)] = m.group(2)

def value(sym, depth=0):
    v = defs[sym]
    if v in defs and depth < 8:
        return value(v, depth + 1)
    return int(v, 0)

rows = []
for line in open(keys_rs):
    m = re.match(r"\s+(\w+)\s*=\s*sys::(KEY_\w+) as _,", line)
    if m and m.group(2) in defs and m.group(1) != "Reserved":
        rows.append((m.group(1), value(m.group(2))))

rows.sort(key=lambda r: r[0].lower())
print("// @generated by tools/gen_keys.py from input-linux 0.7.1 + linux/input-event-codes.h. Don't edit.")
print("/// `(input_linux::Key name, Linux keycode)`, sorted by lowercase name.")
print("pub(crate) const KEYS: &[(&str, u16)] = &[")
for n, v in rows:
    print(f'    ("{n}", {v}),')
print("];")
